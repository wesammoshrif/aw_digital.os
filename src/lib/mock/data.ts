const NOW = new Date("2026-06-06T09:00:00Z");

function id(n: number, prefix = "lead") {
  return `${prefix}-${String(n).padStart(8, "0")}-0000-0000-000000000000`;
}

function date(daysFromNow: number, hours = 0): Date {
  const d = new Date(NOW);
  d.setDate(d.getDate() + daysFromNow);
  d.setHours(d.getHours() + hours);
  return d;
}

